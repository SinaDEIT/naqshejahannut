-- Fresh PostgreSQL schema for the Railway API. No D1 records are imported.
-- Safe to run repeatedly; all existing rows are left untouched.

CREATE TABLE IF NOT EXISTS shop_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  province TEXT,
  city TEXT,
  address TEXT NOT NULL,
  note TEXT,
  items_json TEXT NOT NULL,
  subtotal BIGINT NOT NULL,
  shipping BIGINT NOT NULL,
  total BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'new',
  ip_hash TEXT,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);
CREATE INDEX IF NOT EXISTS idx_orders_created ON shop_orders(created_at);

CREATE TABLE IF NOT EXISTS shop_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pid TEXT,
  name TEXT,
  rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body TEXT NOT NULL,
  approved BOOLEAN NOT NULL DEFAULT FALSE,
  ip_hash TEXT,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);

CREATE TABLE IF NOT EXISTS product_overrides (
  id TEXT PRIMARY KEY,
  data TEXT NOT NULL,
  updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);

CREATE TABLE IF NOT EXISTS rate_hits (
  k TEXT NOT NULL,
  ts BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_hits ON rate_hits(k, ts);

CREATE TABLE IF NOT EXISTS tg_sessions (
  chat TEXT PRIMARY KEY,
  state TEXT NOT NULL DEFAULT '',
  data TEXT NOT NULL DEFAULT '{}',
  updated BIGINT NOT NULL
);

-- Created up front on Railway; fresh database means there is no legacy backfill.
CREATE TABLE IF NOT EXISTS customers (
  phone TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  orders INTEGER NOT NULL DEFAULT 1,
  first_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  last_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  source TEXT NOT NULL DEFAULT 'site'
);
CREATE INDEX IF NOT EXISTS idx_customers_last_at ON customers(last_at DESC, phone);
